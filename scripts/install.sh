#!/usr/bin/env bash
# OmaPoker installer.
#
# Creates a managed virtualenv, installs OmaPoker into it, and drops a launcher
# and a desktop entry for the current user. Nothing is written outside $HOME, so
# no root is involved and there is nothing to be afraid of.
#
#   ./scripts/install.sh              install (editable, from this checkout)
#
# Re-running it is safe: the virtualenv and the launcher are replaced in place.
set -euo pipefail

APP="omapoker"
NAME="OmaPoker"
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SHARE_DIR="${OMAPOKER_SHARE_DIR:-${XDG_DATA_HOME:-$HOME/.local/share}/$APP}"
VENV="$SHARE_DIR/venv"
BIN_DIR="${XDG_BIN_HOME:-$HOME/.local/bin}"
APPS_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/applications"
ICON_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/icons/hicolor/scalable/apps"

green() { printf '\033[38;2;158;206;106m%s\033[0m\n' "$*"; }
dim()   { printf '\033[38;2;86;95;137m%s\033[0m\n' "$*"; }
warn()  { printf '\033[38;2;224;175;104m%s\033[0m\n' "$*" >&2; }

if [ ! -f "$SRC/pyproject.toml" ]; then
  warn "install.sh must live in the OmaPoker checkout (looked in $SRC)."
  exit 1
fi

green "OmaPoker installer"
dim  "  source    $SRC"
dim  "  venv      $VENV"

# ---------------------------------------------------------------- virtualenv
python=""
if command -v uv >/dev/null 2>&1; then
  python="$(command -v uv)"
  dim "  python    uv manage"
  if [ ! -x "$VENV/bin/python" ]; then
    # uv is the Omarchy house tool: it is fast and it already knows about
    # toolchain pythons, so prefer it when it is there.
    uv venv --python 3.11 "$VENV"
  fi
else
  if ! command -v python3 >/dev/null 2>&1; then
    warn "Neither uv nor python3 is available. Install one and try again."
    exit 1
  fi
  if [ ! -x "$VENV/bin/python" ]; then
    python3 -m venv "$VENV"
  fi
fi

# ------------------------------------------------------------------- install
# `identity` pulls in cryptography, which gives profiles their Ed25519 keys.
if [ -n "$python" ]; then
  uv pip install --python "$VENV/bin/python" --upgrade --quiet -e "$SRC[identity]"
else
  "$VENV/bin/python" -m pip install --upgrade --quiet pip
  "$VENV/bin/python" -m pip install --upgrade --quiet -e "$SRC[identity]"
fi
dim "  installed $(cd "$SRC" && "$VENV/bin/python" -c 'import omapoker; print("omapoker", omapoker.__version__)')"

# ------------------------------------------------------------------ launcher
mkdir -p "$BIN_DIR"
cat > "$BIN_DIR/omapoker" <<EOF
#!/usr/bin/env bash
# Generated by OmaPoker's install.sh - edit scripts/install.sh instead.
exec "$VENV/bin/python" -m omapoker "\$@"
EOF
chmod 0755 "$BIN_DIR/omapoker"
dim "  launcher  $BIN_DIR/omapoker"

# ------------------------------------------------------------ icon + .desktop
mkdir -p "$APPS_DIR" "$ICON_DIR"
install -m 0644 "$SRC/assets/omapoker.svg" "$ICON_DIR/omapoker.svg"
sed "s|@EXEC@|$VENV/bin/python -m omapoker|" \
  "$SRC/assets/omapoker.desktop" > "$APPS_DIR/omapoker.desktop"
chmod 0644 "$APPS_DIR/omapoker.desktop"
dim "  desktop   $APPS_DIR/omapoker.desktop"

command -v update-desktop-database >/dev/null 2>&1 &&
  update-desktop-database "$APPS_DIR" >/dev/null 2>&1 || true

# ---------------------------------------------------------------- gate check
echo
if "$VENV/bin/python" -m omapoker --check; then
  green "$NAME is ready. Run: omapoker"
else
  warn "Installed, but this system does not satisfy the Omarchy gate."
  warn "OmaPoker will refuse to start here (that is the point)."
fi
